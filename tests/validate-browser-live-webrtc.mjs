import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFile(path.join(ROOT,p),'utf8');
const manifest = JSON.parse(await read('prstudio-unified-browser-agent/manifest.json'));
const worker = await read('prstudio-unified-browser-agent/service-worker.js');
const live = await read('prstudio-unified-browser-agent/lib/live-webrtc.js');
const offscreen = await read('prstudio-unified-browser-agent/offscreen-live.js');
const panel = await read('prstudio-unified-browser-agent/sidepanel.html');
const server = await read('prstudio-unified-control/includes/class-prstudio-uc-browser-live.php');
const rest = await read('prstudio-unified-control/includes/class-prstudio-uc-rest.php');
const mcp = await read('prstudio-unified-control/includes/class-prstudio-uc-mcp-v5.php');

assert.equal(manifest.name, 'PR STUDIO Unified Browser Agent');
assert.equal(manifest.version, '1.0.0');
assert.deepEqual(manifest.background, { service_worker:'service-worker.js', type:'module' });
assert.equal(manifest.side_panel?.default_path, 'sidepanel.html');
for (const permission of ['activeTab','tabCapture','offscreen','contextMenus']) assert.ok(manifest.permissions.includes(permission));
assert.match(worker, /openPanelOnActionClick:\s*true/);
assert.match(worker, /liveSetupMenus\(\)/);
assert.match(worker, /liveHandleContextMenu/);
assert.match(live, /chrome\.tabCapture\.getMediaStreamId\(\{\s*targetTabId/);
assert.match(live, /chrome\.offscreen\.createDocument/);
assert.match(live, /offscreenCreationPromise/);
assert.match(live, /closeOffscreenIfIdle/);
assert.match(live, /PR STUDIO LIVE WebRTC — Avvia\/Ferma questa scheda/);
assert.match(offscreen, /navigator\.mediaDevices\.getUserMedia/);
assert.match(offscreen, /chromeMediaSource:\s*['"]tab['"]/);
assert.match(offscreen, /new RTCPeerConnection/);
assert.doesNotMatch(offscreen, /MediaRecorder/);
assert.match(panel, /Browser LIVE · WebRTC/);
assert.match(server, /persistent_media_storage'\s*=>\s*false/);
assert.match(server, /private_ephemeral_file/);
for (const prefix of ["data:image/","data:video/","data:audio/"]) assert.ok(server.includes(prefix));
for (const route of ["'/stream/session'", "'/stream/session/(?P<session>[a-f0-9]{32})'"]) assert.ok(rest.includes(route));
for (const tool of ['browser_live_attach','browser_live_signal','browser_live_stop','browser_live_status']) assert.ok(mcp.includes(`self::tool('${tool}'`));
const essentialStart = mcp.indexOf('private const SURFACE_ESSENTIAL');
const essentialEnd = mcp.indexOf('private const TOOLS_LIST_TOKEN_BUDGET', essentialStart);
const essential = mcp.slice(essentialStart, essentialEnd);
for (const tool of ['browser_live_attach','browser_live_signal','browser_live_stop']) assert.ok(essential.includes(`'${tool}'`), `${tool} must be advertised so the Apps widget can call it`);
assert.match(server, /MAX_SIGNALING_BYTES/);
assert.match(server, /function acknowledge/);
assert.match(server, /before !== \$after/);
assert.ok(worker.includes('CONFIG: "prstudioConfig"'), 'pairing storage identity must stay unchanged');
assert.ok(worker.includes('/wp-json/prstudio-unified/v1/pair'), 'pair endpoint must stay unchanged');
console.log('PASS Browser LIVE static contract: same extension identity/update path, tabCapture→offscreen MediaStream→WebRTC, ephemeral signaling, no media persistence.');
